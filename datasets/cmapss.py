class CmapssPartial(Dataset):
    """
    This class will cut the original Cmapss dataset, which is useful while testing small sample scenes.
    """

    def __init__(self,
                 dataset: Cmapss,
                 mode: Union[str, List],
                 ratio: Union[float, List],
                 retrain_max_label: bool = False,
                 rul_sample_mode: str = None):
        """
        :param dataset: The Cmapss dataset.
        :param mode: The mode of cutting 'engine', 'rul' or 'random'.
                     'engine' indicating the cutting along with the engine direction,
                     'rul' indicating the cutting along with the label direction,
                     'random' indicating the absolutely random cutting. This param also could be provided by **list** of above.
                     If a list is provided, the combination processing will be applied.
        :param ratio: The available data ratio, should be (0, 1]. This param shape must be corresponding to the mode param.
        :param retrain_max_label: Whether to retrain the max rul data, only available while mode contains 'rul'.
        :param rul_sample_mode: The sample mode while sampling rul 'early', 'late', 'uniform', only used while mode = 'rul'.
        """
        available_mode = ['rul', 'engine', 'random']
        self.dataset = copy.deepcopy(dataset)
        if isinstance(mode, str):
            mode = [mode]
        if isinstance(ratio, float):
            ratio = [ratio]
        assert len(mode) == len(
            ratio), f"The lengths of param mode must equal the lengths of param ratio, but got {mode} and {ratio}"
        i = 0
        for m in mode:
            assert 0 < ratio[i] <= 1, f"The param 'ratio' must be [0, 1], but got {ratio}."
            assert m in available_mode, f"The cutting mode must be one of the ['rul', 'engine', 'random'], but got {m}."
            self.data = self.dataset.data
            self.labels = self.dataset.labels
            self.ids = self.dataset.ids
            if m == 'engine':
                engines = np.unique(self.ids)
                engine_num = len(engines)
                select_num = int(ratio[i] * engine_num)
                available_engine = np.random.choice(engines, select_num, replace=False)
                target_index = np.where(np.isin(self.ids, available_engine))[0]
            elif m == 'rul':
                all_rul = np.sort(np.unique(self.labels))[::-1]  # descent order
                rul_num = len(all_rul)
                select_num = int(ratio[i] * rul_num)
                available_rul = np.random.choice(all_rul,
                                                 select_num,
                                                 replace=False)
                if retrain_max_label:
                    rul_max = max(all_rul)
                    available_rul = np.sort(available_rul)
                    available_rul[-1] = rul_max
                target_index = np.where(np.isin(self.labels, available_rul))[0]
            else:
                data_num = len(self.data)
                select_num = int(ratio[i] * data_num)
                target_index = np.random.choice(np.arange(0, data_num), select_num, replace=False)
            self.dataset.data = self.data[target_index]
            self.dataset.labels = self.labels[target_index]
            self.dataset.ids = self.ids[target_index]
            i += 1

    def __getitem__(self, item):
        return self.dataset.__getitem__(item)

    def __len__(self):
        return self.dataset.__len__()


def get_partial_data(path: str,
                     subset: Subset, window_size: int,
                     slide_step: int = 1,
                     sensors: list = None,
                     scaler: sklearn.base.TransformerMixin = pre.MinMaxScaler((-1, 1)),
                     rul_threshold=0,
                     label_norm=False,
                     val_ratio=0.2,
                     mode: Union[str, List] = "rul",
                     ratio: Union[float, List] = 0.2,
                     retrain_max_label: bool = True,
                     rul_sample_p: str = None):
    train, test, val, _ = get_data(path,
                                   subset=subset,
                                   window_size=window_size,
                                   slide_step=slide_step,
                                   sensors=sensors,
                                   rul_threshold=rul_threshold,
                                   label_norm=label_norm,
                                   scaler=None,
                                   val_ratio=val_ratio)
    train = CmapssPartial(train, mode, ratio, retrain_max_label, rul_sample_p)
    train_data = train.dataset.data
    test_data = test.data
    B_train, T, N = train_data.shape
    B_test, T, N = test_data.shape
    train_data = train_data.reshape(-1, train_data.shape[-1])
    scaler.fit(train_data)
    train.dataset.data = scaler.transform(train_data).reshape(B_train, T, N)
    test.data = scaler.transform(test_data.reshape(-1, N)).reshape(B_test, T, N)
    if val is not None:
        val_data = val.data
        B_val, T, N = val_data.shape
        val.data = scaler.transform(val_data.reshape(-1, N)).reshape(B_val, T, N)
        return train, test, val, scaler
    return train, test, None, scaler


